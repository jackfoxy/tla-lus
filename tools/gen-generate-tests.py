#!/usr/bin/env python3
"""Generate exact seeded-trace tests for PROBABILISTIC simulation (R2.4.6).

lib/node-eval's psolve family ports tlc2's `Tool.probabilistic` path through
getNextStates -- the CPS walk `-generate` takes, which visits the disjuncts,
the bounded existential, `\\in` and `\\subseteq` in RANDOMIZED order and returns
as soon as the next-state functor accepts one successor. This runs
`tlc2.TLC -generate num=1 -workers 1 -seed S` for a corpus of specs and asserts
that `generate-spec` reproduces the exact behavior AND the exact
states-generated total.

Every case puts its nondeterminism BELOW the action-decomposition boundary,
because that is the only place the flag can be observed: `Tool.getActions`
splits a top-level `\\/` per disjunct and enumerates a top-level `\\E` per
element, leaving nothing for the probabilistic branches to randomize --
measured, `-simulate` and `-generate` are byte-identical on both shapes.

Never edit generated files.
"""
import re
import subprocess
from pathlib import Path

REPO = Path("/mnt/mars/gitrepos/tla-lus")
JAR = Path("/mnt/mars/gitrepos/tlaplus/tlatools/org.lamport.tlatools/dist/tla2tools.jar")
OUT = REPO / "desk/tests/lib/generate-diff.hoon"
WORK = Path("/tmp/gen-generate-work")

# name, source, cfg, depth, seeds. One case per probabilistic opcode.
CASES = [
    # OPCODE_be -- a bounded existential under a conjunction, so getActions
    # stops at the conjunction and the quantifier survives to getNextStates.
    ("exists", """---- MODULE spec ----
EXTENDS Naturals
VARIABLE x, y
Init == x = 0 /\\ y = 0
Next == /\\ y' = y + 1
        /\\ \\E n \\in 1..5 : x' = (x + n) % 100
Inv == x < 90
====
""", "INIT Init\nNEXT Next\nINVARIANT Inv\n", 60, [1, 2, 3]),
    # OPCODE_in -- `x' \in S` is never decomposed, so this shape reaches the
    # probabilistic branch even at the top level; kept under a conjunction so
    # the successor set is what varies rather than the action count.
    ("in", """---- MODULE spec ----
EXTENDS Naturals
VARIABLE x, y
Init == x = 0 /\\ y = 0
Next == /\\ y' = y + 1
        /\\ x' \\in {x + 1, x + 2, x + 7}
Inv == x < 40
====
""", "INIT Init\nNEXT Next\nINVARIANT Inv\n", 60, [1, 2, 3]),
    # OPCODE_dl -- a disjunction under a conjunction. This one draws from the
    # SIMULATION generator (TLCGlobals.simulator.getRNG() returns the worker's
    # localRng on a worker thread), not from the enumeration generator.
    ("disj", """---- MODULE spec ----
EXTENDS Naturals
VARIABLE x, y
Init == x = 0 /\\ y = 0
Next == /\\ y' = y + 1
        /\\ \\/ x' = x + 1
           \\/ x' = x + 4
           \\/ x' = x + 9
Inv == x < 50
====
""", "INIT Init\nNEXT Next\nINVARIANT Inv\n", 60, [1, 2, 3]),
]


def hcord(s: str) -> str:
    o = []
    for ch in s:
        if ch == "\\":
            o.append("\\\\")
        elif ch == "'":
            o.append("\\'")
        elif ch == "\n":
            o.append("\\0a")
        else:
            o.append(ch)
    return "".join(o)


def tlc_generate(src: str, cfg: str, seed: int, depth: int):
    """The behavior `-generate` produces before the invariant trips, each state
    as render-states' "var=val,..." (vars sorted), and the run's total."""
    WORK.mkdir(exist_ok=True)
    (WORK / "spec.tla").write_text(src)
    (WORK / "spec.cfg").write_text(cfg)
    r = subprocess.run(
        ["java", "-cp", str(JAR), "tlc2.TLC", "-generate", "num=1",
         "-depth", str(depth), "-seed", str(seed), "-workers", "1", "spec.tla"],
        cwd=WORK, capture_output=True, text=True)
    lines = r.stdout.splitlines()
    try:
        start = next(i for i, l in enumerate(lines) if "behavior up to this point" in l)
    except StopIteration:
        raise SystemExit(f"no trace for seed {seed}:\n{r.stdout}\n{r.stderr}")
    states, cur = [], None
    for l in lines[start + 1:]:
        if l.startswith("State "):
            if cur is not None:
                states.append(cur)
            cur = {}
        elif cur is not None:
            m = re.match(r"\s*(?:/\\ )?(\w+) = (.+)$", l)
            if m:
                cur[m.group(1)] = m.group(2).strip()
            elif l.strip() == "" and cur:
                pass
            elif not l.startswith(" ") and l.strip():
                break
    if cur:
        states.append(cur)
    gm = re.search(r"The number of states generated: (\d+)", r.stdout)
    if gm is None:
        raise SystemExit(f"no states-generated line for seed {seed}:\n{r.stdout}")
    path = [",".join(f"{k}={v}" for k, v in sorted(s.items())) for s in states]
    return path, int(gm.group(1))


HEADER = """::  GENERATED by tools/gen-generate-tests.py -- do not edit.
::  Exact seeded-trace parity for PROBABILISTIC simulation (R2.4.6): lib/check's
::  generate-spec (the psolve CPS walk in node-eval, drawing java.util.Random
::  through lib/rng for BOTH the worker generator and the enumeration
::  generator) reproduces `tlc2.TLC -generate -workers 1 -seed S` behavior for
::  behavior, and its states-generated total.
/+  *test
/=  check  /lib/check
/=  ne     /lib/node-eval
|%
"""


def main() -> None:
    arms = []
    n = 0
    for name, src, cfg, depth, seeds in CASES:
        arms.append(f"++  src-{name}  '{hcord(src)}'\n")
        arms.append(f"++  cfg-{name}  '{hcord(cfg)}'\n")
        for seed in seeds:
            path, gen = tlc_generate(src, cfg, seed, depth)
            golden = "~[" + " ".join(f'"{p}"' for p in path) + "]"
            arms.append(f"""++  test-gen-{name}-{seed}
  %+  expect-eq
    !>  `(list tape)`{golden}
  !>  %-  render-states:ne
      path:(need viol:(generate-spec:check src-{name} cfg-{name} {seed} 1 {depth}))
++  test-gen-count-{name}-{seed}
  %+  expect-eq
    !>  `@ud`{gen}
  !>  gen:(generate-spec:check src-{name} cfg-{name} {seed} 1 {depth})
""")
            n += 2
    OUT.write_text(HEADER + "".join(arms) + "--\n")
    print(f"{n} generate exact-trace cases")
    print(f"TOTAL {n}")


if __name__ == "__main__":
    main()
