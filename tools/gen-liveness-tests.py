#!/usr/bin/env python3
"""Capture single-worker liveness goldens from the LivenessDump oracle (unit 8).

Each case lives in desk/test-data/liveness/<case>/ as A.tla plus A.txt (the .cfg
content; the desk has no %cfg Clay mark, so the corpus stores it as A.txt) and
an optional opts.txt (one extra tlc2.TLC argument per line). LivenessDump drives
tlc2.TLC single-worker with an MPRecorder, projecting the temporal behaviour the
Hoon liveness engine (lib/{temporal,tableau,liveness}.hoon, unit 8) must match:
the verdict, EC category, the violated property name(s), run statistics, and the
lasso — its per-state FP64 fingerprints and action labels, its loop-target state
number, and its stuttering / back-to-state classification. Timings, worker ids,
thread order, and the on-disk graph layout are excluded.

Until unit 8 grows the temporal/tableau/liveness libs and check.hoon consumes
them, this is ORACLE-ONLY: it only refreshes out.txt. The five gen-mc-tests
liveness goldens (tests/lib/mc: <>P/[]<>P stutter lassos, no fairness) stay the
green smoke suite; this corpus is the parity target those cannot express
(fairness WF_/SF_, ~>, spec-form fairness, non-stuttering and back-to-state
lassos, loop targets, and the symmetry+liveness diagnostic). Never edit
generated files; the A.tla/A.txt/opts.txt inputs are the hand-authored source of
truth.
"""
import shutil
import subprocess
import tempfile
from pathlib import Path

REPO = Path("/mnt/mars/gitrepos/tla-lus")
JAR = Path("/mnt/mars/gitrepos/tlaplus/tlatools/org.lamport.tlatools/dist/tla2tools.jar")
DUMP_CP = f"{JAR}:{REPO}/tools/oracle/build"
CASES = REPO / "desk/test-data/liveness"


def golden(case: Path) -> None:
    opts = []
    if (case / "opts.txt").exists():
        opts = [l for l in (case / "opts.txt").read_text().split("\n") if l.strip()]
    with tempfile.TemporaryDirectory() as td:
        tdp = Path(td)
        shutil.copy(case / "A.tla", tdp / "A.tla")
        shutil.copy(case / "A.txt", tdp / "A.cfg")
        # out.txt: the run projection (verdict, lasso, loop target, class)
        r = subprocess.run(["java", "-cp", DUMP_CP, "LivenessDump", "A"] + opts,
                           cwd=td, capture_output=True, text=True, timeout=180)
        (case / "out.txt").write_text(r.stdout)
        # struct.txt: the normalization projection (OrderOfSolution decomposition
        # — the live-expression / oos / pem parity target for lib/temporal.hoon,
        # unit 8.1). Independent of the extra tlc args (options do not affect the
        # temporal normalization), so LivenessStruct takes no opts.
        s = subprocess.run(["java", "-cp", DUMP_CP, "LivenessStruct", "A"],
                           cwd=td, capture_output=True, text=True, timeout=180)
        (case / "struct.txt").write_text(s.stdout)
        # product.txt: the behavior-graph PRODUCT projection (per OrderOfSolution
        # product node + initial-node counts) — the unit 8.3 parity target for
        # lib/liveness. Drives a standalone LiveCheck over the reachable graph;
        # deterministic per fixture (FP64 index 0, a set not a run order).
        p = subprocess.run(["java", "-cp", DUMP_CP, "ProductDump", "A"],
                           cwd=td, capture_output=True, text=True, timeout=180)
        (case / "product.txt").write_text(p.stdout)


def hcord(s: str) -> str:
    o = []
    for ch in s:
        if ch == "\\":
            o.append("\\\\")
        elif ch == "'":
            o.append("\\'")
        elif ch == "\n":
            o.append("\\0a")
        elif ch == "\t":
            o.append("\\09")
        else:
            o.append(ch)
    return "".join(o)


STRUCT_HEADER = """::  GENERATED by tools/gen-liveness-tests.py -- do not edit.
::  Full structural projection (unit 8.1.3 + R1.6.2): `live-struct-full` must
::  match LivenessStruct's struct.txt for every liveness corpus case -- the
::  OrderOfSolution.toString rendering AND the tableau GRAPH (per node: its
::  index, its particle, its successor indices), not just the node count.
::  Modules are the exact corpus A.tla so Location spans match.
/+  *test
/=  check  /lib/check
|%
"""


# Cases whose struct projection must be taken through the RAW path
# (`+raw-live-oss`), because the production entry point typed-rejects them
# before normalization runs. `symmetry-live` declares SYMMETRY with a liveness
# PROPERTY: tlc2 warns and continues, the port refuses (an 8.7
# approved-difference, compatibility.md), so only the raw path reaches the
# decomposition this shard is here to compare.
STRUCT_RAW = {"symmetry-live"}


def write_struct_shard() -> int:
    """Emit tests/lib/temporal-struct.hoon from the captured struct.txt goldens.

    This shard used to be hand-maintained while claiming to be generated, so a
    projection change meant editing 16 inline goldens by hand (R1.6.2 found it
    when extending TABLEAU to the full graph). It is generated now, which also
    puts it under validate.py's drift guard.
    """
    arms = []
    n = 0
    for case in sorted(CASES.iterdir()):
        if not (case.is_dir() and (case / "A.tla").exists()):
            continue
        arm = case.name.replace("_", "-")
        src = (case / "A.tla").read_text()
        cfg = (case / "A.txt").read_text()
        gold = (case / "struct.txt").read_text()
        lines = [l for l in gold.split("\n")]
        if lines and lines[-1] == "":
            lines.pop()
        items = "\n".join(f"        '{hcord(l)}'" for l in lines)
        entry = ("live-struct-full-raw:check" if case.name in STRUCT_RAW
                 else "live-struct-full:check")
        arms.append(f"""::
++  src-{arm}  '{hcord(src)}'
++  cfg-{arm}  '{hcord(cfg)}'
++  test-struct-{arm}
  %+  expect-eq
    !>  ^-  wain
    :~
{items}
    ==
  !>(({entry} src-{arm} cfg-{arm}))
""")
        n += 1
    out = REPO / "desk/tests/lib/temporal-struct.hoon"
    out.write_text(STRUCT_HEADER + "".join(arms) + "--\n")
    return n


PRODUCT_HEADER = """::  GENERATED by tools/gen-liveness-tests.py -- do not edit.
::  Behavior-graph product (unit 8.3 + R1.6.3): `live-product` must match
::  tools/oracle/ProductDump (desk/test-data/liveness/<case>/product.txt) for
::  every liveness corpus case -- the node/init counts AND the graph itself,
::  each node's checkState bits and each edge's checkAction bits, keyed by
::  fingerprint RANK so no raw FP64 appears in a golden.
/+  *test
/=  check  /lib/check
|%
"""

# Cases excluded from the product differential, each with its reason.
#   symmetry-live: the port refuses SYMMETRY + liveness where tlc2 warns and
#     continues (an 8.7 approved-difference), so production never reaches the
#     product build.
PRODUCT_SKIP = {"symmetry-live"}


def write_product_shard() -> int:
    arms = []
    n = 0
    for case in sorted(CASES.iterdir()):
        if not (case.is_dir() and (case / "A.tla").exists()):
            continue
        if case.name in PRODUCT_SKIP:
            continue
        arm = case.name.replace("_", "-")
        src = (case / "A.tla").read_text()
        cfg = (case / "A.txt").read_text()
        lines = (case / "product.txt").read_text().split("\n")
        if lines and lines[-1] == "":
            lines.pop()
        items = "\n".join(f"        '{hcord(l)}'" for l in lines)
        arms.append(f"""::
++  psrc-{arm}  '{hcord(src)}'
++  pcfg-{arm}  '{hcord(cfg)}'
++  test-product-{arm}
  %+  expect-eq
    !>  ^-  wain
    :~
{items}
    ==
  !>((live-product:check psrc-{arm} pcfg-{arm}))
""")
        n += 1
    out = REPO / "desk/tests/lib/liveness-product.hoon"
    out.write_text(PRODUCT_HEADER + "".join(arms) + "--\n")
    return n


def main() -> None:
    n = 0
    for case in sorted(CASES.iterdir()):
        if case.is_dir() and (case / "A.tla").exists():
            golden(case)
            n += 1
    m = write_struct_shard()
    q = write_product_shard()
    print(f"{n} liveness cases")
    print(f"  struct shard: {m} cases -> tests/lib/temporal-struct.hoon")
    print(f"  product shard: {q} cases -> tests/lib/liveness-product.hoon")
    print(f"TOTAL {n}")


if __name__ == "__main__":
    main()
