#!/usr/bin/env python3
"""Generate simulation-statistics tests (unit 9.3b).

lib/check's simulate reports structured partial statistics: states generated
(|inits| + successors), the behavior count, and the trace-length distribution
(Welford mean/var/sd). This runs `tlc2.TLC -simulate` for completing runs and
asserts simulate-spec reaches the same `The number of states generated: N` and
`trace length: mean=X, var(x)=Y, sd=Z` as the pinned JVM. (Trace length is
uniformly `depth` for non-deadlocking completing runs, so var/sd are 0; the
meaningful varying stat is states-generated.) Never edit generated files.
"""
import re
import subprocess
from pathlib import Path

REPO = Path("/mnt/mars/gitrepos/tla-lus")
JAR = Path("/mnt/mars/gitrepos/tlaplus/tlatools/org.lamport.tlatools/dist/tla2tools.jar")
OUT = REPO / "desk/tests/lib/sim-stats.hoon"
WORK = Path("/tmp/gen-sim-stats-work")

# completing, non-deadlocking, non-violating specs (each behavior runs to depth).
CASES = [
    ("det", """---- MODULE spec ----
EXTENDS Naturals
VARIABLE x
Init == x = 0
Next == x' = x + 1
====
""", "INIT Init\nNEXT Next\n", [(1, 3), (3, 3), (1, 5), (3, 5), (4, 6)]),
    ("twoact", """---- MODULE spec ----
EXTENDS Naturals
VARIABLE x
Init == x = 0
A == x' = x + 1
B == x' = x + 2
Next == A \\/ B
====
""", "INIT Init\nNEXT Next\n", [(3, 4), (5, 6)]),
]
SEED = 1


def hcord(s: str) -> str:
    return "".join({"\\": "\\\\", "'": "\\'", "\n": "\\0a"}.get(c, c) for c in s)


def tlc_stats(src: str, cfg: str, num: int, depth: int):
    WORK.mkdir(exist_ok=True)
    (WORK / "spec.tla").write_text(src)
    (WORK / "spec.cfg").write_text(cfg)
    r = subprocess.run(
        ["java", "-cp", str(JAR), "tlc2.TLC", "-simulate", f"num={num}",
         "-depth", str(depth), "-seed", str(SEED), "-workers", "1", "spec.tla"],
        cwd=WORK, capture_output=True, text=True)
    out = r.stdout
    gen = int(re.search(r"number of states generated: (\d+)", out).group(1))
    m = re.search(r"(\d+) traces generated \(trace length: mean=(\d+), "
                  r"var\(x\)=(\d+), sd=(\d+)\)", out)
    traces, mean, var, sd = (int(g) for g in m.groups())
    return gen, mean, var, sd, traces


HEADER = """::  GENERATED by tools/gen-sim-stats-tests.py -- do not edit.
::  Simulation statistics parity (unit 9.3b): lib/check simulate reports the same
::  states-generated and trace-length mean/var/sd as `tlc2.TLC -simulate`.
/+  *test
/=  check  /lib/check
|%
"""


def main() -> None:
    arms = []
    n = 0
    for name, src, cfg, runs in CASES:
        arms.append(f"++  src-{name}  '{hcord(src)}'\n")
        arms.append(f"++  cfg-{name}  '{hcord(cfg)}'\n")
        for num, depth in runs:
            gen, mean, var, sd, traces = tlc_stats(src, cfg, num, depth)
            arms.append(f"""++  test-sim-stats-{name}-{num}-{depth}
  =/  r  (simulate-spec:check src-{name} cfg-{name} {SEED} {num} {depth})
  %+  expect-eq
    !>  [gen={gen} mean={mean} var={var} sd={sd} traces={traces}]
  !>  [gen.r mean.r var.r sd.r traces.r]
""")
            n += 1
    OUT.write_text(HEADER + "".join(arms) + "--\n")
    print(f"{n} sim statistics cases")
    print(f"TOTAL {n}")


if __name__ == "__main__":
    main()
