#!/usr/bin/env python3
"""Generate Hoon differential lexer tests from the Java oracle.

- Boundary fixtures: desk/test-data/lex/boundary/*.tla with .gold files
  (regenerated here) -> tests/lib/tla/lexer/boundary.hoon
- Syntax corpus: extracts every case from the pinned tlaplus repo's
  test/tla2sany/corpus/*.txt, dumps tokens with TokenDump, writes
  inputs+goldens under desk/test-data/lex/corpus/ and one Hoon test
  shard per corpus file.

Every expected value is oracle output; never edit generated files.
"""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path("/mnt/mars/gitrepos/tla-lus")
TLA = Path("/mnt/mars/gitrepos/tlaplus/tlatools/org.lamport.tlatools")
JAR = TLA / "dist/tla2tools.jar"
DUMP_CP = f"{JAR}:{REPO}/tools/oracle/build"
BOUNDARY = REPO / "desk/test-data/lex/boundary"
CORPUS_SRC = TLA / "test/tla2sany/corpus"
CORPUS_OUT = REPO / "desk/test-data/lex/corpus"
TESTS = REPO / "desk/tests/lib/tla/lexer"


def dump(path: Path) -> str:
    r = subprocess.run(["java", "-cp", DUMP_CP, "TokenDump", str(path)],
                       capture_output=True, text=True, check=True)
    return r.stdout


def hcord(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == "'":
            out.append("\\'")
        elif ch == "\n":
            out.append("\\0a")
        elif ch == "\t":
            out.append("\\09")
        elif ch == "\r":
            out.append("\\0d")
        else:
            out.append(ch)
    return "".join(out)


def emit_case(arm: str, name: str, text: str, gold: str) -> str:
    lines = gold.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    if lines:
        gold_items = "\n".join(f"        '{hcord(l)}'" for l in lines)
        expected = f"    !>  ^-  wain\n    :~\n{gold_items}\n    =="
    else:
        expected = "    !>  *wain"
    return f"""::
::  {name}
++  test-{arm}
  %+  expect-eq
{expected}
  !>((dump:lexer '{hcord(text)}'))
"""


HEADER = """::  GENERATED by tools/gen-lexer-tests.py -- do not edit.
::  Expected values are Java oracle (TokenDump) output at the pinned
::  tlaplus commit; see desk/doc/port-map.md.
/+  *test
/=  lexer  /lib/tla/lexer
|%
"""


def gen_boundary() -> None:
    arms = []
    for tla in sorted(BOUNDARY.glob("*.tla")):
        gold = dump(tla)
        (BOUNDARY / (tla.stem + ".gold")).write_text(gold)
        text = tla.read_text()
        arms.append(emit_case(tla.stem, tla.name, text, gold))
    out = HEADER + "".join(arms) + "--\n"
    TESTS.mkdir(parents=True, exist_ok=True)
    (TESTS / "boundary.hoon").write_text(out)
    print(f"boundary: {len(arms)} cases")
    return len(arms)


MARK_EQ = re.compile(r"^=+\|\|\|$")
MARK_DASH = re.compile(r"^-+\|\|\|$")


def corpus_cases(path: Path):
    lines = path.read_text().split("\n")
    i = 0
    while i < len(lines):
        if not MARK_EQ.match(lines[i]):
            i += 1
            continue
        j = i + 1
        name_lines = []
        while j < len(lines) and not MARK_EQ.match(lines[j]):
            name_lines.append(lines[j])
            j += 1
        j += 1  # closing === marker
        body = []
        while j < len(lines) and not MARK_DASH.match(lines[j]):
            body.append(lines[j])
            j += 1
        # trim leading/trailing blank lines, keep interior
        while body and body[0] == "":
            body.pop(0)
        while body and body[-1] == "":
            body.pop()
        yield " ".join(name_lines).strip(), "\n".join(body) + "\n"
        i = j


def slug(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return s or "case"


def gen_corpus() -> None:
    CORPUS_OUT.mkdir(parents=True, exist_ok=True)
    total = 0
    for src in sorted(CORPUS_SRC.glob("*.txt")):
        base = re.sub(r"[^a-z0-9]+", "-", src.stem.lower()).strip("-")
        arms = []
        for n, (name, body) in enumerate(corpus_cases(src)):
            case_id = f"{base}-{n:03d}"
            inp = CORPUS_OUT / f"{case_id}.tla"
            inp.write_text(body)
            gold = dump(inp)
            (CORPUS_OUT / f"{case_id}.gold").write_text(gold)
            arm = f"{case_id}-{slug(name)}"[:60].rstrip("-")
            arms.append(emit_case(arm, f"{src.name}: {name}", body, gold))
        if not arms:
            continue
        out = HEADER + "".join(arms) + "--\n"
        (TESTS / f"corpus-{base}.hoon").write_text(out)
        total += len(arms)
        print(f"corpus-{base}: {len(arms)} cases")
    print(f"corpus total: {total}")
    return total


if __name__ == "__main__":
    which = sys.argv[1] if len(sys.argv) > 1 else "all"
    n = 0
    if which in ("all", "boundary"):
        n += gen_boundary()
    if which in ("all", "corpus"):
        n += gen_corpus()
    print(f"TOTAL {n}")
