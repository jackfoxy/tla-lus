#!/usr/bin/env python3
"""Regenerate parse-error diagnostic goldens + Hoon shard (P2 unit 2).

Fixtures are every syntax-corpus case SANY rejects (their inputs live in
desk/test-data/parse/corpus/) plus the hand-written malformed modules in
desk/test-data/parse-err/boundary/.  The golden is the verbatim error text
SANY's TLAplusParser pushes onto PErrors (tools/oracle/ParseErrDump.java):
REJECT, then each error terminated by a "%%" line.

Emits desk/tests/lib/tla/parse-err.hoon comparing (dump-err:syntax input)
against each golden.
"""
import re
import subprocess
import sys
from pathlib import Path

REPO = Path("/mnt/mars/gitrepos/tla-lus")
TLA = Path("/mnt/mars/gitrepos/tlaplus/tlatools/org.lamport.tlatools")
JAR = TLA / "dist/tla2tools.jar"
PIN = "4ba7d8811289fb8e95dac4d5e554c05216ba3100"
BUILD = REPO / "tools/oracle/build"
CORPUS = REPO / "desk/test-data/parse/corpus"
BOUNDARY = REPO / "desk/test-data/parse-err/boundary"
OUT = REPO / "desk/test-data/parse-err"
TEST = REPO / "desk/tests/lib/tla/parse-err.hoon"

HEADER = """::  GENERATED by tools/gen-parse-err-tests.py -- do not edit.
::  Expected values are the verbatim PErrors text of SANY's TLAplusParser
::  at the pinned commit (tools/oracle/ParseErrDump.java).
/+  *test
/=  syntax  /lib/tla/syntax
|%
++  wall-cord
  |=  w=wain
  ^-  @t
  (rap 3 (join '\\0a' w))
"""


def check_pin() -> None:
    head = subprocess.run(["git", "-C", str(TLA.parent.parent), "rev-parse", "HEAD"],
                          capture_output=True, text=True).stdout.strip()
    if head != PIN:
        sys.exit(f"tlaplus is {head}, not pinned {PIN}")


def dump(tla: Path) -> str:
    r = subprocess.run(["java", "-cp", f"{JAR}:{BUILD}", "ParseErrDump", str(tla)],
                       capture_output=True, text=True, timeout=60)
    if r.returncode != 0:
        sys.exit(f"ParseErrDump failed on {tla}:\n{r.stderr}")
    return r.stdout


def hcord(text: str) -> str:
    """single-quoted Hoon cord literal"""
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == "'":
            out.append("\\'")
        elif ch == "\n":
            out.append("\\0a")
        elif ch == "\t":
            out.append("\\09")
        elif ch == "\r":
            out.append("\\0d")
        else:
            out.append(ch)
    return "".join(out)


def emit_case(arm: str, src: str, gold: str) -> str:
    return f"""::
++  test-{arm}
  %+  expect-eq
    !>  '{hcord(gold)}'
  !>  (wall-cord (dump-err:syntax '{hcord(src)}'))
"""


def main() -> None:
    check_pin()
    OUT.mkdir(parents=True, exist_ok=True)
    arms = []
    cases = []
    for gold in sorted(CORPUS.glob("*.gold")):
        if gold.read_text().startswith("REJECT"):
            cases.append(("c-" + gold.stem, CORPUS / (gold.stem + ".tla")))
    for tla in sorted(BOUNDARY.glob("*.tla")):
        cases.append(("b-" + tla.stem, tla))
    for name, tla in cases:
        out = dump(tla)
        (OUT / f"{name}.gold").write_text(out)
        arm = re.sub(r"[^a-z0-9-]+", "-", name.lower())
        arms.append(emit_case(arm, tla.read_text(), out.rstrip("\n")))
    TEST.write_text(HEADER + "".join(arms) + "--\n")
    print(f"{len(arms)} parse-err cases")
    print(f"TOTAL {len(arms)}")


if __name__ == "__main__":
    main()
