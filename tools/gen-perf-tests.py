#!/usr/bin/env python3
"""Generate the tier-3 WORKLOAD SET shard (R2.8.1b).

Tier 3 measures the port against ITSELF -- there is no Java answer to a
"how long did it take", which is `doc/testing.md`'s whole argument for keeping
it out of the parity tiers. So this generator has no oracle: the corpus under
`desk/test-data/perf/<workload>/` carries the spec and config, and the WORK
PROFILE beside it is the port's own answer, captured once and then held.

Two things the profile is for, and only the second is obvious:

  * it is what the report reports. R2.8.1b requires the set be
    "byte-reproducible in what it reports", and a wall-clock number never can
    be -- R2.8.1a measured 0.9%-15.6% run-to-run on the same unchanged code.
    The deterministic WORK each workload does (generated / distinct / queued /
    depth / out-degree) is reproducible to the byte, so that is what the shard
    asserts and what a diff of this file shows.
  * it stops a workload from silently ceasing to do its work. A spec that
    starts erroring early would otherwise keep reporting a fast, meaningless
    time -- the perf-harness form of a gate that is not run.

The TIMING rides alongside, read off the test runner's `took` line by
`tools/tier3-noise.py`; nothing inside the ship observes a clock (R2.6.1).

  tools/gen-perf-tests.py --capture   emit the shard in CAPTURE form: every
                                      profile asserted against zeros, so one
                                      ship run prints all the actuals
  tools/gen-perf-tests.py             emit the shard from the stored profiles
"""
import argparse
import re
from pathlib import Path

REPO = Path("/mnt/mars/gitrepos/tla-lus")
CASES = REPO / "desk/test-data/perf"
OUT = REPO / "desk/tests/lib/perf.hoon"

#  the runtime these budgets were measured on. A budget measured elsewhere
#  says nothing here, which is why it is part of the record rather than a
#  comment (R2.8.1b: "stored per pinned runtime")
RUNTIME = "vere 4.6, --loom 32"

HEAD = """::  GENERATED by tools/gen-perf-tests.py -- do not edit.
::
::  The tier-3 WORKLOAD SET (R2.8.1b). One workload per hot path, each
::  asserting the DETERMINISTIC WORK it does; the timing is read off the
::  runner's own `took` line by tools/tier3-noise.py and is deliberately not
::  asserted here -- R2.8.1a measured 0.9%-15.6% run-to-run on unchanged
::  code, so a time is not a fact a test can hold. What IS byte-reproducible
::  is the work, and that is what this file reports.
::
::  NOT A GATE. R2.8.1a's measurement decided tier 3 ships REPORT-ONLY:
::  `release-gate.sh` gets no clause from it. These arms fail only when the
::  port's own work profile CHANGES, which is a regression report, not a
::  threshold.
::
::  Budgets below are measured medians on {runtime}, carried so a later
::  reader can tell a workload that got slower from one that was always slow.
/+  *test
/=  check  /lib/check
|%
++  prof
  ::  the full statistics of a SAFETY search: generated / distinct / queued /
  ::  depth, and the out-degree distribution the wire run-stats does not carry
  |=  [s=@t c=@t]
  ^-  [@ud @ud @ud @ud [@ud @ud @ud @ud]]
  (run-stats-full:check s c 0 1.000)
::
++  lprof
  ::  the LIVENESS workload's profile, and it is a different arm on purpose:
  ::  `+run-stats-full` builds `bfs-opts` with no liveness at all, so timing a
  ::  temporal spec through it measures the safety search and reports a fast,
  ::  meaningless number. Caught by this file's own capture -- the liveness
  ::  workload's profile came back as its 12-state safety graph. `+run-check`
  ::  is the entry point that actually reaches the 8.2-8.6 engine.
  ::  The leading digit is the verdict (1 = %ok), so a workload that starts
  ::  FAILING rather than merely getting slower shows up in the profile
  |=  [s=@t c=@t]
  ^-  [@ud @ud @ud @ud @ud]
  =/  r  (run-check:check s c 0)
  :-  ?:(?=(%ok -.-.r) 1 0)
  [generated.+.r distinct.+.r queued.+.r depth.+.r]
::
"""


def cases():
    for d in sorted(CASES.iterdir()):
        if d.is_dir() and (d / "spec.tla").exists():
            yield d


def hcord(t: str) -> str:
    return (t.replace("\\", "\\\\").replace("'", "\\'")
             .replace("\n", "\\0a").replace("\t", "\\09"))


def hnum(n: int) -> str:
    """Hoon's dot-grouped numeral. A bare `1153` is a SYNTAX ERROR in Hoon --
    numbers past three digits must be written `1.153`, and the build failure
    is reported against the column of the literal, not the file."""
    s = str(n)
    out = []
    while len(s) > 3:
        out.append(s[-3:])
        s = s[:-3]
    out.append(s)
    return ".".join(reversed(out))


def read(d: Path, name: str, default: str = "") -> str:
    f = d / name
    return f.read_text().strip() if f.exists() else default


def profile(d: Path, engine: str) -> str:
    """The stored work profile as a Hoon literal, or zeros when capturing."""
    want = 5 if engine == "liveness" else 8
    p = read(d, "profile.txt")
    if not p:
        return "[0 0 0 0 0]" if want == 5 else "[0 0 0 0 [0 0 0 0]]"
    n = [int(x) for x in re.findall(r"\d+", p)]
    if len(n) != want:
        raise SystemExit(
            f"{d.name}: {engine} profile.txt needs {want} numbers, got {len(n)}")
    h = [hnum(x) for x in n]
    if want == 5:
        return f"[{h[0]} {h[1]} {h[2]} {h[3]} {h[4]}]"
    return f"[{h[0]} {h[1]} {h[2]} {h[3]} [{h[4]} {h[5]} {h[6]} {h[7]}]]"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--capture", action="store_true")
    a = ap.parse_args()

    arms, n = [], 0
    for d in cases():
        spec = hcord((d / "spec.tla").read_text())
        cfg = hcord((d / "spec-cfg.txt").read_text())
        path = read(d, "path.txt", d.name)
        budget = read(d, "budget.txt", "unmeasured")
        engine = read(d, "engine.txt", "safety")
        arm = "lprof" if engine == "liveness" else "prof"
        prof = (profile(d, engine) if not a.capture
                else ("[0 0 0 0 0]" if engine == "liveness"
                      else "[0 0 0 0 [0 0 0 0]]"))
        arms.append(f"++  test-perf-{d.name}")
        arms.append(f"  ::  hot path: {path}  ({engine} engine)")
        arms.append(f"  ::  measured median: {budget}")
        arms.append("  %+  expect-eq")
        arms.append(f"    !>  {prof}")
        arms.append(f"  !>  ({arm} '{spec}' '{cfg}')")
        arms.append("::")
        n += 1
    OUT.write_text(HEAD.format(runtime=RUNTIME) + "\n".join(arms) + "\n--\n")
    print(f"{n} workloads -> {OUT.relative_to(REPO)}"
          + ("  (CAPTURE form: every profile is zeros)" if a.capture else ""))


if __name__ == "__main__":
    main()
