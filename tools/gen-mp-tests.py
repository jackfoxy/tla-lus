"""Regenerate the MP.getMessage differential goldens + Hoon shard (R1.3.5.7.2).

For each (class, code, params) vector, tools/oracle/MPDump.java dumps
tlc2.output.MP.getMessage in BOTH -tool (@!@!@STARTMSG/ENDMSG) and plain
(class-prefix) mode from the pinned jar; the emitted shard compares
(mp-message:diag class code params tool) byte-for-byte.
"""
