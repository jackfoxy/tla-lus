def check_pin() -> None:
    head = subprocess.run(["git", "-C", str(TLA.parent.parent), "rev-parse", "HEAD"],
                          capture_output=True, text=True).stdout.strip()
    if head != PIN:
        sys.exit(f"tlaplus is {head}, not pinned {PIN}")


def dump(vecs) -> str:
    argv = [f"{c}:{code}:" + "|".join(p) for (c, code, p) in vecs]
    r = subprocess.run(["java", "-cp", f"{JAR}:{BUILD}", "MPDump", *argv],
                       capture_output=True, text=True, timeout=60)
    if r.returncode != 0:
        sys.exit(f"MPDump failed:\n{r.stderr}")
    return r.stdout


def parse(out: str):
    # blocks separated by lines: "### <vec>", "--TOOL--", tool.., "--PLAIN--", plain.., "%%"
    blocks = {}
    cur = None
    mode = None
    buf = []
    key = None
    for line in out.split("\n"):
        if line.startswith("### "):
            cur = line[4:]
            blocks[cur] = {"TOOL": None, "PLAIN": None}
            mode = None
        elif line == "--TOOL--":
            mode, buf = "TOOL", []
        elif line == "--PLAIN--":
            blocks[cur]["TOOL"] = "\n".join(buf)
            mode, buf = "PLAIN", []
        elif line == "%%":
            blocks[cur]["PLAIN"] = "\n".join(buf)
            mode = None
        elif mode:
            buf.append(line)
    return blocks


def hcord(text: str) -> str:
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == "'":
            out.append("\\'")
        elif ch == "\n":
            out.append("\\0a")
        elif ch == "\t":
            out.append("\\09")
        else:
            out.append(ch)
    return "".join(out)


def hoon_params(p) -> str:
    if not p:
        return "~"
    return "~[" + " ".join(f"'{hcord(x)}'" for x in p) + "]"


def hoon_num(n: int) -> str:
    """Hoon @ud literal: dot-separated every 3 digits (2104 -> 2.104)."""
    return f"{n:,}".replace(",", ".")


def emit(idx: int, c: int, code: int, p, tool: bool, gold: str) -> str:
    mode = "tool" if tool else "plain"
    yn = "%.y" if tool else "%.n"
    return f"""::
++  test-{code}-{idx}-{mode}
  %+  expect-eq
    !>  '{hcord(gold)}'
  !>  (mp-message:diag {c} {hoon_num(code)} {hoon_params(p)} {yn})
"""


def tool_body(tool_gold: str) -> str:
    """the getMessage0 body = between the STARTMSG line and the ENDMSG line."""
    return tool_gold.split("\n", 1)[1].rsplit("\n", 1)[0]


def emit_dr(idx: int, c: int, code: int, body: str, tool: bool, gold: str) -> str:
    # diag-render over a typed `diagnostic` whose `message` is the MP body
    mode = "tool" if tool else "plain"
    yn = "%.y" if tool else "%.n"
    sev = "%warning" if c == 3 else "%error"
    return f"""::
++  test-dr-{code}-{idx}-{mode}
  %+  expect-eq
    !>  '{hcord(gold)}'
  !>
  %+  diag-render:diag
    `diagnostic`[[%tlc {hoon_num(code)}] {sev} %config '{hcord(body)}' ~ ~]
  {yn}
"""


def main() -> None:
    check_pin()
    out = dump(VECTORS)
    blocks = parse(out)
    arms = []
    for idx, (c, code, p) in enumerate(VECTORS):
        key = f"{c}:{code}:" + "|".join(p)
        b = blocks[key]
        arms.append(emit(idx, c, code, p, True, b["TOOL"]))
        arms.append(emit(idx, c, code, p, False, b["PLAIN"]))
        # diag-render: serialize a typed diagnostic carrying the MP body
        body = tool_body(b["TOOL"])
        arms.append(emit_dr(idx, c, code, body, True, b["TOOL"]))
        arms.append(emit_dr(idx, c, code, body, False, b["PLAIN"]))
    TEST.write_text(HEADER + "".join(arms) + "--\n")
    print(f"{len(arms)} mp cases ({len(VECTORS)} vectors x 4: mp-message+diag-render, 2 modes)")


if __name__ == "__main__":
    main()
