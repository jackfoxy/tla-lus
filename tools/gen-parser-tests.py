#!/usr/bin/env python3
"""Generate Hoon differential parser tests from the Java oracle (AstDump).

Usage: gen-parser-tests.py [corpus-file-stem ...]
Without args, all corpus files. Writes goldens under
desk/test-data/parse/corpus/ and shards tests/lib/tla/syntax/corpus-*.hoon.
Never edit generated files.
"""
import re
import subprocess
import sys
from pathlib import Path

REPO = Path("/mnt/mars/gitrepos/tla-lus")
TLA = Path("/mnt/mars/gitrepos/tlaplus/tlatools/org.lamport.tlatools")
JAR = TLA / "dist/tla2tools.jar"
DUMP_CP = f"{JAR}:{REPO}/tools/oracle/build"
CORPUS_SRC = TLA / "test/tla2sany/corpus"
CORPUS_OUT = REPO / "desk/test-data/parse/corpus"
TESTS = REPO / "desk/tests/lib/tla/syntax"


def dump(path: Path) -> str:
    r = subprocess.run(["java", "-cp", DUMP_CP, "AstDump", str(path)],
                       capture_output=True, text=True, check=True)
    return r.stdout


def hcord(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == "'":
            out.append("\\'")
        elif ch == "\n":
            out.append("\\0a")
        elif ch == "\t":
            out.append("\\09")
        elif ch == "\r":
            out.append("\\0d")
        else:
            out.append(ch)
    return "".join(out)


def emit_case(arm: str, name: str, text: str, gold: str) -> str:
    lines = gold.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    if lines:
        gold_items = "\n".join(f"        '{hcord(l)}'" for l in lines)
        expected = f"    !>  ^-  wain\n    :~\n{gold_items}\n    =="
    else:
        expected = "    !>  *wain"
    return f"""::
::  {name}
++  test-{arm}
  %+  expect-eq
{expected}
  !>((dump:syntax '{hcord(text)}'))
"""


HEADER = """::  GENERATED by tools/gen-parser-tests.py -- do not edit.
::  Expected values are Java oracle (AstDump) output at the pinned
::  tlaplus commit; see desk/doc/port-map.md.
/+  *test
/=  syntax  /lib/tla/syntax
|%
"""

MARK_EQ = re.compile(r"^=+\|\|\|$")
MARK_DASH = re.compile(r"^-+\|\|\|$")


def corpus_cases(path: Path):
    lines = path.read_text().split("\n")
    i = 0
    while i < len(lines):
        if not MARK_EQ.match(lines[i]):
            i += 1
            continue
        j = i + 1
        name_lines = []
        while j < len(lines) and not MARK_EQ.match(lines[j]):
            name_lines.append(lines[j])
            j += 1
        j += 1
        body = []
        while j < len(lines) and not MARK_DASH.match(lines[j]):
            body.append(lines[j])
            j += 1
        while body and body[0] == "":
            body.pop(0)
        while body and body[-1] == "":
            body.pop()
        yield " ".join(name_lines).strip(), "\n".join(body) + "\n"
        i = j


def slug(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return s or "case"


def main() -> None:
    only = set(sys.argv[1:])
    CORPUS_OUT.mkdir(parents=True, exist_ok=True)
    TESTS.mkdir(parents=True, exist_ok=True)
    total = 0
    for src in sorted(CORPUS_SRC.glob("*.txt")):
        base = re.sub(r"[^a-z0-9]+", "-", src.stem.lower()).strip("-")
        if only and base not in only:
            continue
        arms = []
        for n, (name, body) in enumerate(corpus_cases(src)):
            case_id = f"{base}-{n:03d}"
            inp = CORPUS_OUT / f"{case_id}.tla"
            inp.write_text(body)
            gold = dump(inp)
            (CORPUS_OUT / f"{case_id}.gold").write_text(gold)
            arm = f"{case_id}-{slug(name)}"[:60].rstrip("-")
            arms.append(emit_case(arm, f"{src.name}: {name}", body, gold))
        if not arms:
            continue
        out = HEADER + "".join(arms) + "--\n"
        (TESTS / f"corpus-{base}.hoon").write_text(out)
        total += len(arms)
        print(f"corpus-{base}: {len(arms)} cases")
    print(f"total: {total}")


if __name__ == "__main__":
    main()
