#!/usr/bin/env python3
"""Generate temporal-property-in-simulation tests (unit 9.3a).

lib/check's simulate checks a temporal PROPERTY over each completed behavior's
stutter graph (tlc2 LiveCheck.checkTrace via the 8.2-8.6 engine). This runs
`tlc2.TLC -simulate num=K -depth D -workers 1 -seed S` for temporal-property
specs, records whether TLC reported a violation and how many traces it generated
(the trace count at which it stopped, or `num` when the property holds), and
emits desk/tests/lib/sim-live.hoon asserting simulate-spec reaches the same
verdict and trace count. Never edit generated files.
"""
import re
import subprocess
from pathlib import Path

REPO = Path("/mnt/mars/gitrepos/tla-lus")
JAR = Path("/mnt/mars/gitrepos/tlaplus/tlatools/org.lamport.tlatools/dist/tla2tools.jar")
OUT = REPO / "desk/tests/lib/sim-live.hoon"
WORK = Path("/tmp/gen-sim-live-work")

# temporal-property specs. `liv` is violated on the first behavior every seed
# (the trace's stutter-at-x=0 loop always breaks <>[](x=1)); `hold` holds under
# stuttering (x stays 0, so []<>(x=0) is satisfied) so all `num` traces complete.
CASES = [
    ("liv", """---- MODULE spec ----
EXTENDS Naturals
VARIABLE x
Init == x = 0
A == x' = 1 - x
B == x' = x
Next == A \\/ B
Live == <>[](x = 1)
====
""", "INIT Init\nNEXT Next\nPROPERTY Live\n", 3, 8, [1, 2, 3, 7, 42]),
    ("hold", """---- MODULE spec ----
EXTENDS Naturals
VARIABLE x
Init == x = 0
Next == x' = x
Live == []<>(x = 0)
====
""", "INIT Init\nNEXT Next\nPROPERTY Live\n", 3, 5, [1, 2, 3, 7, 42]),
]


def hcord(s: str) -> str:
    o = []
    for ch in s:
        o.append({"\\": "\\\\", "'": "\\'", "\n": "\\0a"}.get(ch, ch))
    return "".join(o)


def tlc_verdict(src: str, cfg: str, num: int, depth: int, seed: int):
    """(traces, kind) where kind is 'property' if TLC reported a temporal
    violation else 'none', and traces is TLC's generated-trace count."""
    WORK.mkdir(exist_ok=True)
    (WORK / "spec.tla").write_text(src)
    (WORK / "spec.cfg").write_text(cfg)
    r = subprocess.run(
        ["java", "-cp", str(JAR), "tlc2.TLC", "-simulate", f"num={num}",
         "-depth", str(depth), "-seed", str(seed), "-workers", "1", "spec.tla"],
        cwd=WORK, capture_output=True, text=True)
    out = r.stdout
    violated = "was violated" in out
    m = re.search(r"(\d+) traces generated", out)
    traces = int(m.group(1)) if m else num
    return traces, ("property" if violated else "none")


HEADER = """::  GENERATED by tools/gen-sim-live-tests.py -- do not edit.
::  Temporal-property-in-simulation parity (unit 9.3a): lib/check simulate checks
::  a PROPERTY over each behavior's stutter graph and reaches the same verdict +
::  trace count as `tlc2.TLC -simulate -workers 1 -seed S`.
/+  *test
/=  check  /lib/check
|%
"""


def main() -> None:
    arms = []
    n = 0
    for name, src, cfg, num, depth, seeds in CASES:
        arms.append(f"++  src-{name}  '{hcord(src)}'\n")
        arms.append(f"++  cfg-{name}  '{hcord(cfg)}'\n")
        for seed in seeds:
            traces, kind = tlc_verdict(src, cfg, num, depth, seed)
            arms.append(f"""++  test-sim-live-{name}-{seed}
  =/  r  (simulate-spec:check src-{name} cfg-{name} {seed} {num} {depth})
  %+  expect-eq
    !>  [{traces} %{kind}]
  !>  [traces.r ?~(viol.r %none kind.u.viol.r)]
""")
            n += 1
    OUT.write_text(HEADER + "".join(arms) + "--\n")
    print(f"{n} sim temporal-property cases")
    print(f"TOTAL {n}")


if __name__ == "__main__":
    main()
