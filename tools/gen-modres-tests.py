#!/usr/bin/env python3
"""Generate module-resolution differential tests.

Cases live in desk/test-data/modres/<case>/ as .tla files with A.tla as
the root. Goldens come from `tla2sany.SANY -s` (normalized: absolute
paths and jar suffixes stripped from Parsing lines, trailing blank runs
collapsed). Emits tests/lib/tla/modres.hoon comparing
(dump-modres:modules root inline-map) against each golden.
Never edit generated files.
"""
import re
import subprocess
from pathlib import Path

REPO = Path("/mnt/mars/gitrepos/tla-lus")
JAR = Path("/mnt/mars/gitrepos/tlaplus/tlatools/org.lamport.tlatools/dist/tla2tools.jar")
CASES = REPO / "desk/test-data/modres"
OUT = REPO / "desk/tests/lib/tla/modres.hoon"


def hcord(s: str) -> str:
    o = []
    for ch in s:
        if ch == "\\":
            o.append("\\\\")
        elif ch == "'":
            o.append("\\'")
        elif ch == "\n":
            o.append("\\0a")
        elif ch == "\t":
            o.append("\\09")
        else:
            o.append(ch)
    return "".join(o)


def golden(case: Path) -> str:
    r = subprocess.run(
        ["java", "-cp", str(JAR), "tla2sany.SANY", "-s", "A.tla"],
        cwd=case, capture_output=True, text=True)
    out = r.stdout + r.stderr
    lines = []
    for l in out.split("\n"):
        m = re.match(r"^Parsing file .*[/\\]([A-Za-z0-9_]+)\.tla.*$", l)
        if m:
            lines.append(f"Parsing file {m.group(1)}.tla")
        else:
            lines.append(l.rstrip())
    # collapse trailing blank run to exactly zero trailing blanks
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + "\n"


HEADER = """::  GENERATED by tools/gen-modres-tests.py -- do not edit.
::  Goldens are normalized `tla2sany.SANY -s` output at the pinned
::  commit; see desk/doc/port-map.md.
/+  *test
/=  modules  /lib/tla/modules
|%
++  trim-blanks
  |=  w=wain
  ^-  wain
  =/  r  (flop w)
  |-
  ?~  r  ~
  ?:  =('' i.r)  $(r t.r)
  (flop r)
"""


def main() -> None:
    arms = []
    for case in sorted(CASES.iterdir()):
        if not case.is_dir():
            continue
        gold = golden(case)
        (case / "golden.txt").write_text(gold)
        glines = gold.split("\n")
        if glines and glines[-1] == "":
            glines.pop()
        gitems = "\n".join(f"        '{hcord(l)}'" for l in glines)
        mods = []
        for f in sorted(case.glob("*.tla")):
            mods.append(f"      :-  '{f.stem}'\n"
                        f"      '{hcord(f.read_text())}'")
        mitems = "\n".join(mods)
        arms.append(f"""::
++  test-modres-{case.name}
  %+  expect-eq
    !>  ^-  wain
    :~
{gitems}
    ==
  !>
  %-  trim-blanks
  %+  dump-modres:modules  'A'
  %-  malt
  ^-  (list [@t @t])
  :~
{mitems}
  ==
""")
    OUT.write_text(HEADER + "".join(arms) + "--\n")
    print(f"{len(arms)} cases")
    print(f"TOTAL {len(arms)}")


if __name__ == "__main__":
    main()
