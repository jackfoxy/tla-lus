#!/usr/bin/env python3
"""Generate DFID differential tests from TLC.

Each case lives in desk/test-data/dfid/<case>/ as spec.tla + spec-cfg.txt +
depth.txt (the `-dfid` bound). `tlc2.TLC -workers 1 -dfid <depth>` is run to
capture the terminal output into out.txt, normalized by stripping the
timestamped/parsing noise. Emits tests/lib/dfid.hoon comparing the trimmed
(dfid-check:check spec cfg depth) output against out.txt.

THE TRACE IS NOT ALWAYS A PARITY TARGET. `DFIDWorker.getInit`/`getNext`
descend into a RANDOM eligible successor from a clock-seeded generator that
`-seed` does not reach, so on a branching spec two runs of the SAME jar report
different counterexamples (R2.5.0). This generator therefore runs the jar
RUNS times per case and keeps only what every run agreed on: if the trace
lines differ, they are dropped from the golden and the case is recorded as
trace-nondeterministic in trace.txt. That marker is STICKY -- a case seen to
vary once stays varying -- so a rare disagreement cannot un-mark itself on a
later regeneration and make this generator irreproducible. Counts, level lines and the verdict are
order-independent and are always compared.

Never edit generated files.
"""
import re
import shutil
import subprocess
from pathlib import Path

REPO = Path("/mnt/mars/gitrepos/tla-lus")
JAR = Path("/mnt/mars/gitrepos/tlaplus/tlatools/org.lamport.tlatools/dist/tla2tools.jar")
CASES = REPO / "desk/test-data/dfid"
OUT = REPO / "desk/tests/lib/dfid.hoon"
RUNS = 8

DROP = re.compile(
    r"WARNING|reflect|jline|illegal|Parsing |Semantic |Linting |"
    r"^Starting\.\.\.|Computing |throughput|nowarning|garbage|Running break|"
    r"Running depth-first|Estimates|because two|calculated |based on the |"
    r"Finished in|^TLC2 Version|Trace exploration|"
    # liveness-engine setup lines: tlc2 builds the tableau BEFORE
    # DFIDModelChecker's constructor refuses, so they precede the refusal.
    # The port refuses at config routing and never builds one -- the same
    # normalization gen-mc-tests.py applies
    r"^Implied-temporal|^Checking temporal|Finished checking temporal")

STATE_HDR = re.compile(r"^State \d+:")
BIND = re.compile(r"^(/\\ )?[A-Za-z_][A-Za-z0-9_]* = ")


def tlc(case: Path, depth: str) -> str:
    shutil.copy(case / "spec-cfg.txt", case / "spec.cfg")
    r = subprocess.run(
        ["java", "-cp", str(JAR), "tlc2.TLC", "-workers", "1", "-dfid", depth,
         "spec.tla"],
        cwd=case, capture_output=True, text=True, timeout=180)
    (case / "spec.cfg").unlink(missing_ok=True)
    for junk in list(case.glob("spec_TTrace_*")) + list(case.glob("*.old")):
        junk.unlink(missing_ok=True)
    st = case / "states"
    if st.is_dir():
        shutil.rmtree(st, ignore_errors=True)
    # NOT rstrip()ed: DFID's two trace printers differ in TRAILING WHITESPACE
    # ("State N: " for an invariant violation, "State N:" for a deadlock or
    # runtime error), and that difference is part of what this compares
    return "\n".join(l.rstrip("\r\n") for l in (r.stdout + r.stderr).split("\n")
                     if l.strip() and not DROP.search(l))


def strip_trace(lines):
    """drop the rendered trace states, keeping every other line"""
    out, in_trace = [], False
    for l in lines:
        if STATE_HDR.match(l):
            in_trace = True
            continue
        if in_trace and BIND.match(l):
            continue
        in_trace = False
        out.append(l)
    return out


def hcord(s: str) -> str:
    return (s.replace("\\", "\\\\").replace("'", "\\'")
             .replace("\n", "\\0a").replace("\t", "\\09").replace("\r", "\\0d"))


HEADER = """::  GENERATED by tools/gen-dfid-tests.py -- do not edit.
::  Expected values are normalized `tlc2.TLC -workers 1 -dfid N` output at the
::  pinned commit, agreed across {runs} runs of the jar. A case whose
::  COUNTEREXAMPLE varied between those runs has its trace states dropped from
::  the golden and `trace.txt` set to `nondeterministic` -- the DFS order is
::  drawn from a clock-seeded generator, so the trace is an approved
::  difference (R2.5.0).
/+  *test
/=  check  /lib/check
|%
++  trim
  ::  drop blank lines; TLC's blank separators between trace states carry
  ::  no information and the captured golden has them removed
  |=  w=wain
  ^-  wain
  (skip w |=(l=@t =('' l)))
::
++  drop-trace
  ::  the counterexample this case produced is not a function of the spec (see
  ::  the header), so only the lines around it are compared
  |=  w=wain
  ^-  wain
  %+  skip  w
  |=  l=@t
  =/  t=tape  (trip l)
  ?:  =("State " (scag 6 t))  &
  ?:  =("/\\\\ " (scag 3 t))  &
  ?=(^ (find " = " t))
""".format(runs=RUNS)


def main() -> None:
    arms, nondet = [], []
    for case in sorted(CASES.iterdir()):
        if not (case / "spec.tla").exists():
            continue
        depth = (case / "depth.txt").read_text().strip()
        marker = case / "trace.txt"
        # STICKY: once a case has been seen to vary, it stays varying. A rare
        # disagreement must not silently un-mark itself on a later regeneration
        # and make this generator non-reproducible under validate.py
        was_nondet = marker.exists() and marker.read_text().strip() == "nondeterministic"
        runs = [tlc(case, depth).split("\n") for _ in range(RUNS)]
        stable = all(r == runs[0] for r in runs[1:]) and not was_nondet
        if stable:
            glines = runs[0]
            marker.write_text("deterministic\n")
        else:
            stripped = [strip_trace(r) for r in runs]
            assert all(s == stripped[0] for s in stripped[1:]), (
                f"{case.name}: runs disagree outside the trace")
            glines = stripped[0]
            nondet.append(case.name)
            marker.write_text("nondeterministic\n")
        (case / "out.txt").write_text("\n".join(glines) + "\n")
        gitems = "\n".join(f"        '{hcord(l)}'" for l in glines)
        spec = hcord((case / "spec.tla").read_text())
        cfg = hcord((case / "spec-cfg.txt").read_text())
        body = "%-  trim" if stable else "%-  drop-trace\n  %-  trim"
        arms.append(f"""::
++  test-dfid-{case.name}
  %+  expect-eq
    !>  ^-  wain
    :~
{gitems}
    ==
  !>
  {body}
  %^  dfid-check:check
    '{spec}'
  '{cfg}'
  {depth}
""")
    OUT.write_text(HEADER + "".join(arms) + "--\n")
    print(f"{len(arms)} dfid cases, {len(nondet)} trace-nondeterministic: "
          f"{', '.join(nondet) if nondet else 'none'}")
    print(f"TOTAL {len(arms)}")


if __name__ == "__main__":
    main()
