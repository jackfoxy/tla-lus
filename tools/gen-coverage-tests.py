#!/usr/bin/env python3
"""Coverage-block differential (R2.7.4.2b), from the safety corpus.

`tlc-coverage`'s counters are reported by `CostModelCreator.report()` as five
line kinds. SafetyDump projects the four that are FACTS about the run --
`TLC_COVERAGE_INIT`, `_NEXT`, `_PROPERTY` (the invariants, which carry no
counts) and `_CONSTRAINT` -- each rendered exactly as MP renders it, in the
pin's own report order. This script emits desk/tests/lib/coverage.hoon
comparing `+check-cov:check`'s block against those lines, one arm per case.

Two line kinds are deliberately NOT compared, both declared approved
differences in desk/doc/compatibility.md and both absent from the projection:
the per-VARIABLE `TLC_COVERAGE_VAR` count (a `SyncedHyperLogLog(10)` ESTIMATE
over `v.fingerPrint(FP64.New())`, which also pins the run to `-fp 0`) and the
indented per-node sub-expression lines (`TLC_COVERAGE_VALUE`/`_COST`), which
are `getEvalCount()` inside evaluation.

Only cases whose `opts.txt` asks for `-coverage` are emitted, and only ones
that ended `VERDICT ok` WITHOUT a counterexample: a run that prints a trace
inflates every counter, because tlc2 re-invokes the initial predicate and the
actions to reconstruct it with coverage still recording (measured: `<A …>: 2:2`
becomes `2:6`). The port refuses to report coverage for such a run rather than
publishing a different number under the same name, and `+test-coverage-refused`
below pins that refusal.
"""
import re
import sys
import subprocess
from pathlib import Path

REPO = Path("/mnt/mars/gitrepos/tla-lus")
TLA = Path("/mnt/mars/gitrepos/tlaplus/tlatools/org.lamport.tlatools")
PIN = "4ba7d8811289fb8e95dac4d5e554c05216ba3100"
CASES = REPO / "desk/test-data/safety"
TEST = REPO / "desk/tests/lib/coverage.hoon"

HEADER = """::  GENERATED by tools/gen-coverage-tests.py -- do not edit.
::  The `-coverage` block vs tlc2's CostModelCreator.report(), projected by
::  tools/oracle/SafetyDump.java at the pinned commit (R2.7.4.2b). Each arm
::  compares every line the port emits between the header and `End of
::  statistics.` against the pin's, in the pin's order.
/+  *test
/=  check  /lib/check
|%
::  the coverage block's lines, header and footer stripped -- exactly the part
::  SafetyDump's `COVERAGE` records project
++  cov-block
  |=  w=wain
  ^-  (list @t)
  =/  ls  w
  |-  ^-  (list @t)
  ?~  ls  ~
  ?.  =('The coverage statistics ' (end [3 24] i.ls))  $(ls t.ls)
  =/  rest  t.ls
  |-  ^-  (list @t)
  ?~  rest  ~
  ?:  =('End of statistics.' i.rest)  ~
  [i.rest $(rest t.rest)]
"""


def check_pin() -> None:
    h = subprocess.run(["git", "-C", str(TLA.parent.parent), "rev-parse", "HEAD"],
                       capture_output=True, text=True).stdout.strip()
    if h != PIN:
        sys.exit(f"tlaplus is {h}, not pinned {PIN}")


def hcord(t: str) -> str:
    return (t.replace("\\", "\\\\").replace("'", "\\'")
             .replace("\n", "\\0a").replace("\t", "\\09"))


def main() -> None:
    check_pin()
    arms, n = [], 0
    for case in sorted(CASES.iterdir()):
        if not (case.is_dir() and (case / "opts.txt").exists()):
            continue
        if "-coverage" not in (case / "opts.txt").read_text():
            continue
        out = (case / "out.txt").read_text()
        if not re.search(r"^VERDICT ok$", out, re.M):
            continue
        if not re.search(r"^TRACE 0$", out, re.M):
            continue
        lines = [l[len("COVERAGE "):] for l in out.split("\n")
                 if l.startswith("COVERAGE ")]
        if not lines:
            continue
        tla = (case / "A.tla").read_text()
        cfg = (case / "A.txt").read_text()
        arm = re.sub(r"[^a-z0-9]+", "-", case.name.lower())
        want = "\n".join(f"        '{hcord(l)}'" for l in lines)
        arms.append(f"""::
++  test-{arm}-block
  %+  expect-eq
    !>  ^-  (list @t)
    :~
{want}
    ==
  !>  (cov-block (check-cov:check '{hcord(tla)}' '{hcord(cfg)}'))
""")
        n += 1
    TEST.write_text(HEADER + "".join(arms) + "--\n")
    print(f"{n} coverage cases")
    print(f"TOTAL {n}")


if __name__ == "__main__":
    main()
