#!/usr/bin/env python3
"""Generate TLC .cfg parse tests from the ConfigDump oracle (unit 5).

Each case lives in desk/test-data/cfg/<case>/in.txt. Goldens come from
`ConfigDump in.txt` (a normalized, UID-free projection of the ModelConfig
config AST + rawConstants, or a CONFIG-ERROR section with the exact
ConfigFileException message). This captures each case's golden.txt and
emits desk/tests/lib/cfg.hoon comparing (dump-cfg:config 'in-text')
against each golden. Never edit generated files.

Input files use the .txt extension, written before the desk had a `%cfg`
mark (R4.0e); ModelConfig parses either identically.
"""
import subprocess
from pathlib import Path

REPO = Path("/mnt/mars/gitrepos/tla-lus")
JAR = Path("/mnt/mars/gitrepos/tlaplus/tlatools/org.lamport.tlatools/dist/tla2tools.jar")
DUMP_CP = f"{JAR}:{REPO}/tools/oracle/build"
CASES = REPO / "desk/test-data/cfg"
OUT = REPO / "desk/tests/lib/cfg.hoon"


def hcord(s: str) -> str:
    o = []
    for ch in s:
        if ch == "\\":
            o.append("\\\\")
        elif ch == "'":
            o.append("\\'")
        elif ch == "\n":
            o.append("\\0a")
        elif ch == "\t":
            o.append("\\09")
        else:
            o.append(ch)
    return "".join(o)


def golden(case: Path) -> str:
    r = subprocess.run(["java", "-cp", DUMP_CP, "ConfigDump", "in.txt"],
                       cwd=case, capture_output=True, text=True)
    (case / "golden.txt").write_text(r.stdout)
    return r.stdout


HEADER = """::  GENERATED by tools/gen-cfg-tests.py -- do not edit.
::  Goldens are normalized ConfigDump output at the pinned tlaplus commit
::  (tlc2.tool.impl.ModelConfig parse projection); see desk/doc/port-map.md.
/+  *test
/=  config  /lib/config
|%
"""


def main() -> None:
    arms = []
    n = 0
    for case in sorted(CASES.iterdir()):
        if not (case.is_dir() and (case / "in.txt").exists()):
            continue
        gold = golden(case)
        src = (case / "in.txt").read_text()
        arm = case.name.replace("_", "-")
        arms.append(f"""::
++  test-cfg-{arm}
  %+  expect-eq
    !>  `@t`'{hcord(gold)}'
  !>  (dump-cfg:config '{hcord(src)}')
""")
        n += 1
    OUT.write_text(HEADER + "".join(arms) + "--\n")
    print(f"{n} cfg cases")
    print(f"TOTAL {n}")


if __name__ == "__main__":
    main()
