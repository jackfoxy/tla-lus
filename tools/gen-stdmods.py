#!/usr/bin/env python3
"""Embed tla2sany/StandardModules/*.tla into lib/tla/stdmods.hoon.

Source: pinned tlaplus commit (doc/port-map.md section 1), MIT license.
Never edit the generated file.
"""
from pathlib import Path

SRC = Path("/mnt/mars/gitrepos/tlaplus/tlatools/org.lamport.tlatools/src/tla2sany/StandardModules")
OUT = Path("/mnt/mars/gitrepos/tla-lus/desk/lib/tla/stdmods.hoon")


def hcord(s: str) -> str:
    o = []
    for ch in s:
        if ch == "\\":
            o.append("\\\\")
        elif ch == "'":
            o.append("\\'")
        elif ch == "\n":
            o.append("\\0a")
        elif ch == "\t":
            o.append("\\09")
        elif ch == "\r":
            o.append("\\0d")
        else:
            o.append(ch)
    return "".join(o)


entries = []
for f in sorted(SRC.glob("*.tla")):
    entries.append(f"  :-  '{f.stem}'\n  '{hcord(f.read_text())}'")
body = "\n".join(entries)
OUT.write_text(f"""|%
  ::  Vendored TLA+ Standard Modules
  ::
  ::  GENERATED by tools/gen-stdmods.py from
  ::  tla2sany/StandardModules/*.tla at the pinned tlaplus commit
  ::  (doc/port-map.md section 1). MIT license, (c) the TLA+ project
  ::  contributors; notices retained in the module texts below.
  ::  Searched after caller modules, matching SANY shadowing rules.
  ::
++  standard-modules
  ^-  (map @t @t)
  %-  malt
  ^-  (list [@t @t])
  :~
{body}
  ==
--
""")
print(f"{len(entries)} modules, {OUT.stat().st_size} bytes")
print(f"TOTAL {len(entries)}")
