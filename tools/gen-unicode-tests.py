#!/usr/bin/env python3
"""Generate the Unicode differential tests (R4.4, clause 8).

  desk/test-data/unicode/<case>/ascii/*.tla
      the case's modules in ASCII, A.tla the root (written for this suite,
      not taken from any upstream).
  desk/test-data/unicode/<case>/unicode/*.tla
      the same modules converted with the pinned `tlauc --skip numsets`
      (CI's flags), written here. tlauc output: desk/test-data/unicode/
      carries tlauc's license.txt (tools/gen-licenses.py --check).
  desk/test-data/unicode/<case>/golden-{ascii,unicode}.txt
      SemDump of each root at the pinned tlaplus commit.

Generation fails unless the two goldens are identical with every span's
columns elided (tlauc keeps lines and changes symbol widths): the oracle's
own statement of clause 8's structural identity. Emits
desk/tests/lib/unicode.hoon, which compares the port's +dump-sem of each
variant with its golden, columns included, and its +sany-verdict on the
conversion with SANY's. Never edit generated files.
"""
import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path("/mnt/mars/gitrepos/tla-lus")
JAR = Path("/mnt/mars/gitrepos/tlaplus/tlatools/org.lamport.tlatools/dist/tla2tools.jar")
DUMP_CP = f"{JAR}:{REPO}/tools/oracle/build"
TLAUC = Path("/mnt/mars/gitrepos/r4-deps/tlauc")
CASES = REPO / "desk/test-data/unicode"
OUT = REPO / "desk/tests/lib/unicode.hoon"
SPAN = re.compile(r"(\d+)\.\d+-(\d+)\.\d+")


def hcord(s: str) -> str:
    o = []
    for ch in s:
        if ch == "\\":
            o.append("\\\\")
        elif ch == "'":
            o.append("\\'")
        elif ch == "\n":
            o.append("\\0a")
        elif ch == "\t":
            o.append("\\09")
        else:
            o.append(ch)
    return "".join(o)


def semdump(d: Path) -> list:
    r = subprocess.run(["java", "-cp", DUMP_CP, "SemDump", "A.tla"],
                       cwd=d, capture_output=True, text=True, check=True)
    lines = [l.rstrip() for l in r.stdout.split("\n")]
    while lines and lines[-1] == "":
        lines.pop()
    return lines


def verdict(d: Path) -> str:
    r = subprocess.run(["java", "-cp", str(JAR), "tla2sany.SANY", "A.tla"],
                       cwd=d, capture_output=True, text=True)
    return "accept" if r.returncode == 0 else "reject"


def convert(case: Path):
    uni = case / "unicode"
    shutil.rmtree(uni, ignore_errors=True)
    uni.mkdir()
    for f in sorted((case / "ascii").glob("*.tla")):
        shutil.copy2(f, uni / f.name)
        subprocess.run([str(TLAUC), str(uni / f.name), "--skip", "numsets"],
                       check=True, capture_output=True)


def src_map(d: Path) -> str:
    rows = []
    for f in sorted(d.glob("*.tla")):
        rows.append(f"      :-  '{f.stem}'\n"
                    f"      '{hcord(f.read_text(encoding='utf-8'))}'")
    return ("  %-  malt\n  ^-  (list [@t @t])\n  :~\n"
            + "\n".join(rows) + "\n  ==\n")


def wain(lines: list) -> str:
    return ("    !>  ^-  wain\n    :~\n"
            + "".join(f"        '{hcord(l)}'\n" for l in lines)
            + "    ==\n")


def main() -> int:
    arms = []
    for case in sorted(p for p in CASES.iterdir() if (p / "ascii").is_dir()):
        convert(case)
        g = {}
        for v in ("ascii", "unicode"):
            g[v] = semdump(case / v)
            (case / f"golden-{v}.txt").write_text("\n".join(g[v]) + "\n",
                                                 encoding="utf-8")
        ea = [SPAN.sub(r"\1-\2", l) for l in g["ascii"]]
        eu = [SPAN.sub(r"\1-\2", l) for l in g["unicode"]]
        if ea != eu:
            print(f"{case.name}: the oracle's dumps differ beyond columns",
                  file=sys.stderr)
            return 1
        sv = verdict(case / "unicode")
        n = case.name
        for v in ("ascii", "unicode"):
            arms.append(f"::\n++  test-unicode-{n}-sem-{v}\n"
                        f"  %+  expect-eq\n{wain(g[v])}  !>\n"
                        f"  %+  dump-sem:semantic  'A'\n"
                        + src_map(case / v))
        arms.append(f"::\n++  test-unicode-{n}-verdict\n"
                    f"  %+  expect-eq\n    !>  %{sv}\n  !>\n"
                    f"  %+  sany-verdict:semantic  'A'\n"
                    + src_map(case / "unicode"))
    head = ("::  GENERATED by tools/gen-unicode-tests.py -- do not edit.\n"
            "::  R4.4 (clause 8): modules converted by the pinned tlauc\n"
            "::  (--skip numsets); goldens are SemDump at the pinned tlaplus\n"
            "::  commit, identical between the variants with columns elided.\n"
            "/+  *test\n/=  semantic  /lib/semantic\n|%\n")
    OUT.write_text(head + "".join(arms) + "--\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}: {len(arms)} arms")
    print(f"TOTAL {len(arms)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
