#!/usr/bin/env python3
"""Generate java.util.Random parity tests from the RngDump oracle (unit 9.1).

lib/rng ports tlc2.util.RandomGenerator (which extends java.util.Random) so
seeded simulation traces match TLC. This runs RngDump for a fixed seed list and
emits desk/tests/lib/rng.hoon, comparing lib/rng's nextInt/nextLong/nextDouble/
nextPrime and the setSeed(seed,cnt) fast-forward against the pinned JVM output.
Java seeds are passed to Hoon as their unsigned two's-complement atoms (only the
low 48 bits survive seed scrambling, so sign is irrelevant). Never edit
generated files.
"""
import subprocess
from pathlib import Path

REPO = Path("/mnt/mars/gitrepos/tla-lus")
JAR = Path("/mnt/mars/gitrepos/tlaplus/tlatools/org.lamport.tlatools/dist/tla2tools.jar")
DUMP_CP = f"{JAR}:{REPO}/tools/oracle/build"
OUT = REPO / "desk/tests/lib/rng.hoon"

# fixed seed corpus: 0, 1, 42, -1, a mid value, Long.MIN, Long.MAX, a TLC-ish
# seed. 0/Long.MIN and -1/Long.MAX collapse under the 48-bit mask, proving the
# scramble; the rest spread the LCG state space.
SEEDS = [0, 1, 42, -1, 123456789, -9223372036854775808, 9223372036854775807, 8675309]


def label(s: int) -> str:
    return str(s).replace("-", "neg")


def uhex(s: int) -> int:
    return s & ((1 << 64) - 1)


def dot_hex(v: int) -> str:
    h = format(v, "x")
    parts = []
    while len(h) > 4:
        parts.insert(0, h[-4:])
        h = h[:-4]
    parts.insert(0, h)
    return "0x" + ".".join(parts)


def dot_dec(v: int) -> str:
    s = str(v)
    parts = []
    while len(s) > 3:
        parts.insert(0, s[-3:])
        s = s[:-3]
    parts.insert(0, s)
    return ".".join(parts)


def hlist_hex(vals) -> str:
    return "~[" + " ".join(dot_hex(int(x, 16)) for x in vals) + "]"


def hlist_dec(vals) -> str:
    return "~[" + " ".join(dot_dec(int(x)) for x in vals) + "]"


HEADER = """::  GENERATED by tools/gen-rng-tests.py -- do not edit.
::  java.util.Random / tlc2.util.RandomGenerator parity (unit 9.1): lib/rng
::  draws vs the pinned JVM. Seeds are unsigned two's-complement atoms.
/+  *test
/=  rng  /lib/rng
|%
++  n-ints
  ::  the first `n` nextInt draws from `seed` (32-bit two's-complement atoms)
  |=  [seed=@ n=@]
  ^-  (list @)
  =/  s  (scramble:rng seed)
  |-  ^-  (list @)
  ?:  =(n 0)  ~
  =^  v  s  (next-int:rng s)
  [v $(n (dec n))]
++  n-longs
  ::  the first `n` nextLong draws from `seed` (64-bit two's-complement atoms)
  |=  [seed=@ n=@]
  ^-  (list @)
  =/  s  (scramble:rng seed)
  |-  ^-  (list @)
  ?:  =(n 0)  ~
  =^  v  s  (next-long:rng s)
  [v $(n (dec n))]
++  n-dbls
  ::  the first `n` nextDouble draws from `seed`, as raw IEEE-754 double bits
  |=  [seed=@ n=@]
  ^-  (list @)
  =/  s  (scramble:rng seed)
  |-  ^-  (list @)
  ?:  =(n 0)  ~
  =^  v  s  (next-double:rng s)
  [`@`v $(n (dec n))]
++  n-primes
  ::  the first `n` nextPrime draws from `seed`
  |=  [seed=@ n=@]
  ^-  (list @)
  =/  s  (scramble:rng seed)
  |-  ^-  (list @)
  ?:  =(n 0)  ~
  =^  v  s  (next-prime:rng s)
  [v $(n (dec n))]
"""


def main() -> None:
    r = subprocess.run(["java", "-cp", DUMP_CP, "RngDump"] + [str(s) for s in SEEDS],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit("RngDump failed:\n" + r.stderr)
    blocks = {}
    cur = None
    for line in r.stdout.splitlines():
        f = line.split()
        if not f:
            continue
        if f[0] == "SEED":
            cur = {}
            blocks[f[1]] = cur
        else:
            cur[f[0]] = f[1:]

    arms = []
    for s in SEEDS:
        b = blocks[format(uhex(s), "x")]
        sd = dot_hex(uhex(s))
        arms.append(f"""::
++  test-rng-{label(s)}
  ;:  weld
    (expect-eq !>(`(list @)`{hlist_hex(b['INT'])}) !>((n-ints {sd} 10)))
    (expect-eq !>(`(list @)`{hlist_hex(b['LONG'])}) !>((n-longs {sd} 10)))
    (expect-eq !>(`(list @)`{hlist_hex(b['DBL'])}) !>((n-dbls {sd} 10)))
    (expect-eq !>(`(list @)`{hlist_dec(b['PRIME'])}) !>((n-primes {sd} 10)))
    %+  expect-eq
      !>({dot_hex(int(b['SEEDCNT4'][0], 16))})
    !>(`@`-:(next-long:rng (seed-cnt:rng {sd} 4)))
  ==
""")
    OUT.write_text(HEADER + "".join(arms) + "--\n")
    n = len(SEEDS)
    print(f"{n} rng seed cases")
    print(f"TOTAL {n}")


if __name__ == "__main__":
    main()
