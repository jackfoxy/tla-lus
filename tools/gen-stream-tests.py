#!/usr/bin/env python3
"""Ordered init/next STATE STREAM differential (Work Unit 7 / R1.5.10).

`tlc-safety-stategen`'s residue was that the port's state streams keep
branch/binding order but were only spot-tested, never differentially compared.
This closes that: tools/oracle/StreamDump.java projects exactly what
Tool.getInitStates / getNextStates return IN ORDER (successors concatenated
over getActions() in action order — the sequence ModelChecker.doNext walks),
and this script emits desk/tests/lib/stream.hoon comparing the Hoon
+solve-init / +solve-next streams against it byte-for-byte.

Reuses the safety corpus (desk/test-data/safety/<case>/A.tla + A.txt); the
golden is stream.txt beside the existing out.txt.

Two case shapes are skipped, both deliberately and both covered elsewhere:
SPECIFICATION-form configs (no INIT/NEXT pair to drive; R1.5.13/WU8), and
configs declaring CONSTANT (the stream entry points take a module, not a
config — run-check covers that path, and the single such case, symmetry, has
its own tlc-safety-symmetry parity row).
"""
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path("/mnt/mars/gitrepos/tla-lus")
TLA = Path("/mnt/mars/gitrepos/tlaplus/tlatools/org.lamport.tlatools")
JAR = TLA / "dist/tla2tools.jar"
PIN = "4ba7d8811289fb8e95dac4d5e554c05216ba3100"
DUMP_CP = f"{JAR}:{REPO}/tools/oracle/build"
CASES = REPO / "desk/test-data/safety"
TEST = REPO / "desk/tests/lib/stream.hoon"

HEADER = """::  GENERATED by tools/gen-stream-tests.py -- do not edit.
::  Ordered init/next state streams vs tlc2 Tool.getInitStates/getNextStates
::  (tools/oracle/StreamDump.java, R1.5.10) plus the state-graph out-degree
::  distribution vs SafetyDump's STAT outdegree (R1.5.12b), at the pinned commit.
/+  *test
/=  ne  /lib/node-eval
/=  check  /lib/check
|%
++  wc  |=(w=wain ^-(@t (rap 3 (join '\\0a' w))))
::  `var = value` per binding, with NO `/\\ ` conjunct prefix -- the Java
::  side strips it too (`StreamDump.java:45`, "TLC renders conjuncts"),
::  because this projection compares stream ORDER, not console rendering.
::  Using the console `+render-state` here would couple the two: it gained
::  the faithful `TLCStateMut.toString` prefix in R1.1.R1 and broke these
::  two-variable cases. `~` for the variable order feeds `+state-pairs`'s
::  sorted tail (the binding-order approved difference, compatibility.md).
++  binds
  |=  st=state:check
  ^-  (list @t)
  %+  turn  (state-pairs:check ~ st)
  |=([k=@t v=@t] (rap 3 ~[k ' = ' v]))
::  one `S <i> <var = v; var = v>` line per state, in stream order
++  render-stream
  |=  sts=(list state:check)
  ^-  wain
  =/  i=@ud  0
  |-  ^-  wain
  ?~  sts  ~
  :_  $(sts t.sts, i +(i))
  %-  crip
  "S {(a-co:co i)} {(trip (rap 3 (join '; ' (binds i.sts))))}"
"""


def check_pin() -> None:
    h = subprocess.run(["git", "-C", str(TLA.parent.parent), "rev-parse", "HEAD"],
                       capture_output=True, text=True).stdout.strip()
    if h != PIN:
        sys.exit(f"tlaplus is {h}, not pinned {PIN}")


def dump(case: Path) -> str:
    with tempfile.TemporaryDirectory() as td:
        shutil.copy(case / "A.tla", Path(td) / "A.tla")
        shutil.copy(case / "A.txt", Path(td) / "A.cfg")
        r = subprocess.run(["java", "-cp", DUMP_CP, "StreamDump", "A"],
                           cwd=td, capture_output=True, text=True, timeout=180)
    return r.stdout if r.returncode == 0 else ""


def parse(out: str):
    """-> (init_lines, [next_lines_per_initial_state]) or None if unusable."""
    if not out.startswith("STREAM"):
        return None
    init, nexts, mode, cur = [], [], None, []
    for line in out.split("\n"):
        if line.startswith("INIT "):
            mode, cur = "init", []
        elif line == "ENDINIT":
            init, mode = cur, None
        elif line.startswith("NEXT "):
            mode, cur = "next", []
        elif line == "ENDNEXT":
            nexts.append(cur)
            mode = None
        elif line.startswith("S ") and mode:
            cur.append(line)
    return init, nexts


def outdeg(case: Path):
    """the oracle's `STAT outdegree <min> <mean> <p95> <max>` for a case."""
    out = case / "out.txt"
    if not out.exists():
        return None
    for line in out.read_text().split("\n"):
        if line.startswith("STAT outdegree "):
            return line.split()[2:]
    return None


def hcord(t: str) -> str:
    return (t.replace("\\", "\\\\").replace("'", "\\'")
             .replace("\n", "\\0a").replace("\t", "\\09"))


def defname(tla: str, key: str) -> str:
    m = re.search(rf"^{key}\s*==", tla, re.M)
    return key if m else ""


def main() -> None:
    check_pin()
    arms, n = [], 0
    for case in sorted(CASES.iterdir()):
        if not (case.is_dir() and (case / "A.tla").exists()):
            continue
        tla = (case / "A.tla").read_text()
        cfg = (case / "A.txt").read_text()
        # the stream differential needs a plain INIT/NEXT pair to drive
        im = re.search(r"^INIT\s+(\w+)", cfg, re.M)
        nm = re.search(r"^NEXT\s+(\w+)", cfg, re.M)
        if not (im and nm):
            continue                      # SPECIFICATION-form: R1.5.13/WU8
        if re.search(r"^CONSTANT", cfg, re.M):
            # +solve-init/+solve-next take a module, not a config, so a spec
            # whose Init/Next reads a cfg CONSTANT cannot be driven through
            # them. That path runs through run-check, whose verdict/counts the
            # SafetyDump differential already covers, and the one such case
            # (symmetry) has its own parity row (tlc-safety-symmetry).
            continue
        out = dump(case)
        p = parse(out)
        if not p:
            continue
        init, nexts = p
        (case / "stream.txt").write_text(out)
        arm = re.sub(r"[^a-z0-9]+", "-", case.name.lower())
        arms.append(f"""::
++  test-stream-{arm}-init
  %+  expect-eq
    !>  '{hcord(chr10.join(init))}'
  !>
  =/  r  (solve-init:ne 'A' (malt ~[['A' '{hcord(tla)}']]) '{im.group(1)}')
  ?:(?=(%| -.r) 'SOLVE-FAILED' (wc (render-stream p.r)))
""")
        n += 1
        od = outdeg(case)
        if od:
            arms.append(f"""::
++  test-outdeg-{arm}
  %+  expect-eq
    !>  ^-  [@ud @ud @ud @ud]
    [{od[0]} {od[1]} {od[2]} {od[3]}]
  !>
  =/  r  (run-stats-full:check '{hcord(tla)}' '{hcord(cfg)}' 0 1.024)
  [min.outdeg.r mean.outdeg.r p95.outdeg.r max.outdeg.r]
""")
            n += 1
        # successors of each initial state, in stream order
        for si, nx in enumerate(nexts):
            arms.append(f"""::
++  test-stream-{arm}-next-{si}
  %+  expect-eq
    !>  '{hcord(chr10.join(nx))}'
  !>
  =/  src  (malt ~[['A' '{hcord(tla)}']])
  =/  ir  (solve-init:ne 'A' src '{im.group(1)}')
  ?:  ?=(%| -.ir)  'INIT-FAILED'
  ?:  (lth (lent p.ir) {si + 1})  'NO-SUCH-INIT-STATE'
  =/  r  (solve-next:ne 'A' src '{nm.group(1)}' (snag {si} p.ir))
  ?:(?=(%| -.r) 'SOLVE-FAILED' (wc (render-stream p.r)))
""")
            n += 1
    TEST.write_text(HEADER + "".join(arms) + "--\n")
    print(f"{n} stream cases")
    print(f"TOTAL {n}")


chr10 = "\n"

if __name__ == "__main__":
    main()
