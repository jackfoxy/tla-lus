#!/usr/bin/env python3
"""Generate constant-evaluation differential tests from the TLC REPL oracle.

Reads desk/test-data/eval/exprs.txt (one constant TLA+ expression per line),
evaluates each with `tlc2.REPL`, and emits tests/lib/eval.hoon comparing
(eval-text:eval '<expr>') against the REPL's rendered value. Expressions the
REPL rejects render as "Error evaluating expression". Never edit generated
files.
"""
import subprocess
from pathlib import Path

REPO = Path("/mnt/mars/gitrepos/tla-lus")
JAR = Path("/mnt/mars/gitrepos/tlaplus/tlatools/org.lamport.tlatools/dist/tla2tools.jar")
EXPRS = REPO / "desk/test-data/eval/exprs.txt"
OUT = REPO / "desk/tests/lib/eval.hoon"


def repl(exprs):
    r = subprocess.run(["java", "-cp", str(JAR), "tlc2.REPL"],
                       input="\n".join(exprs) + "\n",
                       capture_output=True, text=True, timeout=180)
    out = []
    for line in r.stdout.split("\n"):
        if line.startswith("(tla+) "):
            out.append(line[len("(tla+) "):])
    # the last prompt has no result; align with inputs
    return out[:len(exprs)]


def hcord(s):
    "for a single-quoted Hoon cord"
    return s.replace("\\", "\\\\").replace("'", "\\'")


def htape(s):
    "for a double-quoted Hoon tape"
    return s.replace("\\", "\\\\").replace('"', '\\"')


HEADER = """::  GENERATED by tools/gen-eval-tests.py -- do not edit.
::  Expected values are tlc2.REPL output at the pinned tlaplus commit.
/+  *test
/=  eval  /lib/eval
|%
"""


def main():
    exprs = [l for l in EXPRS.read_text().split("\n") if l.strip()]
    results = repl(exprs)
    arms = []
    for i, (ex, res) in enumerate(zip(exprs, results)):
        arms.append(f"""::
++  test-eval-{i:03d}
  %+  expect-eq
    !>  '{hcord(res)}'
  !>  (crip (eval-text:eval '{hcord(ex)}'))
""")
    OUT.write_text(HEADER + "".join(arms) + "--\n")
    print(f"{len(arms)} eval cases")
    print(f"TOTAL {len(arms)}")


if __name__ == "__main__":
    main()
