#!/usr/bin/env python3
"""Generate semantic-graph differential tests from the SemDump oracle.

Cases live in desk/test-data/sem/<case>/ as .tla files with A.tla as the
root. Goldens come from `SemDump A.tla` (normalized semantic tree with
post-levelCheck levels and DIAGS; volatile UIDs omitted). Emits
desk/tests/lib/sem.hoon comparing (dump-sem:semantic 'A' inline-map)
against each golden.

SemDump's trailing LEVELS section (per-def level-constraint projection:
max-levels, weights, higher-order min-max/level conditions, level params,
level/arg-level constraints, arg-level params, non-Leibniz params) is
still split into golden-lvl.txt per case for inspection, and since unit
4.1 the Hoon renderer emits the same projection: each test arm compares
the full output (tree + DIAGS + LEVELS) as one wain. Never edit
generated files.
"""
import subprocess
from pathlib import Path

REPO = Path("/mnt/mars/gitrepos/tla-lus")
JAR = Path("/mnt/mars/gitrepos/tlaplus/tlatools/org.lamport.tlatools/dist/tla2tools.jar")
DUMP_CP = f"{JAR}:{REPO}/tools/oracle/build"
CASES = REPO / "desk/test-data/sem"
OUT = REPO / "desk/tests/lib/sem.hoon"


def hcord(s: str) -> str:
    o = []
    for ch in s:
        if ch == "\\":
            o.append("\\\\")
        elif ch == "'":
            o.append("\\'")
        elif ch == "\n":
            o.append("\\0a")
        elif ch == "\t":
            o.append("\\09")
        else:
            o.append(ch)
    return "".join(o)


def golden(case: Path) -> tuple[str, str]:
    """Returns (tree+diags golden, LEVELS golden); the generated suite
    compares their concatenation."""
    r = subprocess.run(["java", "-cp", DUMP_CP, "SemDump", "A.tla"],
                       cwd=case, capture_output=True, text=True)
    out = r.stdout
    lines = [l.rstrip() for l in out.split("\n")]
    while lines and lines[-1] == "":
        lines.pop()
    if "LEVELS" in lines:
        cut = lines.index("LEVELS")
        main, lvl = lines[:cut], lines[cut:]
    else:
        main, lvl = lines, []
    return ("\n".join(main) + "\n",
            "\n".join(lvl) + "\n" if lvl else "")


HEADER = """::  GENERATED by tools/gen-sem-tests.py -- do not edit.
::  Goldens are normalized SemDump output at the pinned tlaplus commit
::  (volatile UIDs and the level field omitted); see desk/doc/port-map.md.
/+  *test
/=  semantic  /lib/semantic
|%
"""


# Measured divergences whose arm is withheld (the `SKIPS` idiom of
# gen-core-eval / gen-mc). Each names its ledger row.
SKIPS = {
    "inst-lambda": "R4.2c: the tree agrees (the WITH substitution is SANY's "
                   "`oparg LAMBDA`, the point of the case); the LEVELS "
                   "projection differs on one datum -- SANY's maxLevel of "
                   "M!Ok's parameter is 2 through the LAMBDA operator "
                   "argument, the port's 3. Dump-only (no verdict moves); "
                   "tracker row R4.2an",
    "inst-def-order": "R4.1b: the defs an INSTANCE imports enter the "
                      "instancer's context in java.util.Hashtable order over "
                      "the instancee's context (Generator getByClass), so "
                      "SemDump lists R!Next before R!vars; the port lists "
                      "declaration order. Dump-only (no verdict moves); "
                      "tracker row R4.2ac",
    "inst-noparam": "R4.5.1: an INSTANCE of a module with no CONSTANT or "
                    "VARIABLE -- the port's dump wraps each imported body "
                    "in `substin subs=0`, SemDump has no SubstIn node there. "
                    "Dump-only; the wrapper carries the instanced module for "
                    "the level check and the overrides. Ledger "
                    "`sem-substin-zero` (approved-difference), asserted by "
                    "tests/lib/sem-approved",
    #  subst-arity: un-withheld by R4.1c (2026-10-10), when the renderer
    #  stopped masking the instancee's nodes under an error in the root
}

# Cases whose arm compares only the DIAGS lines (the verdict and its
# diagnostics), for a dump divergence that is recorded elsewhere.
DIAGS_ONLY = {
    "mdef-inner": "R4.2ar: SemDump nests an inner module's own section "
                  "(MODULE Inner, its definitions and LEVELS rows) in the "
                  "parent's dump; the port's dump has never rendered inner "
                  "modules (ledger `sem-inner-module-dump`, approved). The "
                  "diagnostic, found inside the inner module, is the point "
                  "of the case",
    "mdef-inner-ext": "R4.2ar: as mdef-inner (the inner module's own "
                      "section); the point is that NO diagnostic appears -- "
                      "the inner module's EXTENDS B does not put B's "
                      "VARIABLE m in the parent's scope",
}


def main() -> None:
    arms = []
    for case in sorted(CASES.iterdir()):
        if not case.is_dir():
            continue
        gold, lvl = golden(case)
        (case / "golden.txt").write_text(gold)
        lvlf = case / "golden-lvl.txt"
        if lvl:
            lvlf.write_text(lvl)
        elif lvlf.exists():
            lvlf.unlink()
        if case.name in SKIPS:
            #  the golden is still CAPTURED (the next increment has a target);
            #  only the arm is withheld, and the reason is printed every run
            print(f"  SKIP {case.name}: {SKIPS[case.name]}")
            continue
        glines = (gold + lvl).split("\n")
        if glines and glines[-1] == "":
            glines.pop()
        only = case.name in DIAGS_ONLY
        if only:
            print(f"  DIAGS-ONLY {case.name}: {DIAGS_ONLY[case.name]}")
            glines = [l for l in glines if l.startswith("D ")]
        gitems = "\n".join(f"        '{hcord(l)}'" for l in glines)
        mods = []
        for f in sorted(case.glob("*.tla")):
            mods.append(f"      :-  '{f.stem}'\n"
                        f"      '{hcord(f.read_text())}'")
        mitems = "\n".join(mods)
        dump = (f"""  %+  dump-sem:semantic  'A'
  %-  malt
  ^-  (list [@t @t])
  :~
{mitems}
  ==
""")
        if only:
            dump = ("  %+  skim\n"
                    + "".join("  " + l + "\n" for l in dump.splitlines())
                    + "  |=(l=@t =('D ' (end [3 2] l)))\n")
        want = (f"    :~\n{gitems}\n    ==\n" if glines else "    ~\n")
        arms.append(f"""::
++  test-sem-{case.name}
  %+  expect-eq
    !>  ^-  wain
{want}  !>
{dump}""")
    OUT.write_text(HEADER + "".join(arms) + "--\n")
    print(f"{len(arms)} cases")
    print(f"TOTAL {len(arms)}")


if __name__ == "__main__":
    main()
